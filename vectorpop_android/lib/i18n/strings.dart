/// Déduit la langue supportée à partir de la locale système (ex: 'es_ES' -> 'es').
/// Retourne 'en' si la langue de l'appareil n'est pas dans les 15 langues supportées.
String defaultLangFromLocale(String localeName) {
  final code = localeName.split(RegExp(r'[_-]')).first.toLowerCase();
  return kLanguages.any((l) => l.code == code) ? code : 'en';
}

