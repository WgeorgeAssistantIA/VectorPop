/// Fonction de traduction globale avec repli sur l'anglais puis français.
/// Supporte à la fois les paramètres %param% et {param} pour une résilience maximale.
String tr(String lang, String key, [Map<String, String>? params, String? fallback]) {
  var text = kStrings[lang]?[key] ??
      kStrings['en']?[key] ??
      kStrings[kDefaultLang]?[key] ??
      fallback ??
      key;

  if (params != null && params.isNotEmpty) {
    params.forEach((k, v) {
      text = text.replaceAll('%$k%', v);
      text = text.replaceAll('{$k}', v);
    });
  }
  return text;
}
